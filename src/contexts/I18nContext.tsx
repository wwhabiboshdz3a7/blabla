type TranslationKey = keyof typeof translations.fr

const I18nCtx = createContext<{ lang: Lang; t: (key: TranslationKey) => string; setLang: (l: Lang) => void }>({
  lang: 'fr',
  t: (key) => key,
  setLang: () => {},
})

export function useI18n() {
  return useContext(I18nCtx)
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    return (localStorage.getItem('fanni-lang') as Lang) || 'fr'
  })

  useEffect(() => {
    localStorage.setItem('fanni-lang', lang)
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr'
    document.documentElement.lang = lang
  }, [lang])

  const t = (key: TranslationKey): string => {
    return translations[lang][key] || translations.fr[key] || key
  }

  return (
    <I18nCtx.Provider value={{ lang, t, setLang }}>
      {children}
    </I18nCtx.Provider>
  )
}
